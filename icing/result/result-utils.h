#ifndef ICING_RESULT_RESULT_UTILS_H_
#define ICING_RESULT_RESULT_UTILS_H_

#include <cstdint>
#include <optional>
#include <string_view>
#include <utility>

#include "icing/proto/search.pb.h"
#include "icing/schema/schema-store.h"
#include "icing/store/document-filter-data.h"
#include "icing/store/document-store.h"
#include "icing/store/namespace-id.h"

namespace icing {
namespace lib {

namespace result_utils {

using ResultGroupingEntryId = int32_t;

// Returns the ResultGroupingEntryId associated with the given namespace
// and schema.
//
// NOTE: ResultGroupingEntryIds that are generated by calls with different
// ResultGroupingTypes should not be compared. Returned ResultGroupingEntryIds
// are only guaranteed to be unique within their own ResultGroupingType.
//
// Returns:
// - A valid ResultGroupingEntryId on success
// - std::nullopt there is no such result grouping entry id (e.g. result group
//   type is not supported, result group type is based on the given
//   namespace/schema but the namespace/schema doesn't exist).
std::optional<ResultGroupingEntryId> EncodeResultGroupingEntryId(
    const SchemaStore& schema_store, const DocumentStore& document_store,
    ResultSpecProto::ResultGroupingType result_group_type,
    std::string_view name_space, std::string_view schema);

// Returns the ResultGroupingEntryId associated with the given NamespaceId
// and SchemaTypeId.
//
// NOTE: ResultGroupingEntryIds that are generated by calls with different
// ResultGroupingTypes should not be compared. Returned ResultGroupingEntryIds
// are only guaranteed to be unique within their own ResultGroupingType.
//
// Returns:
// - A valid ResultGroupingEntryId on success
// - std::nullopt if there is no such result grouping entry id (result group
//   type is not supported).
std::optional<ResultGroupingEntryId> EncodeResultGroupingEntryId(
    ResultSpecProto::ResultGroupingType result_group_type,
    NamespaceId namespace_id, SchemaTypeId schema_type_id);

// Decodes the ResultGroupingEntryId into the associated NamespaceId and
// SchemaTypeId, according to the given ResultGroupingType.
//
// NOTE: different ResultGroupingTypes use different fields, and it is possible
//   that the returned NamespaceId or SchemaTypeId is invalid. For example, if
//   ResultGroupingType is SCHEMA_TYPE, the returned NamespaceId will be
//   kInvalidNamespaceId.
//
// Returns: a pair of NamespaceId and SchemaTypeId corresponding to the given
//   ResultGroupingEntryId and ResultGroupingType.
std::pair<NamespaceId, SchemaTypeId> DecodeResultGroupingEntryId(
    ResultGroupingEntryId result_grouping_entry_id,
    ResultSpecProto::ResultGroupingType result_group_type);

}  // namespace result_utils

}  // namespace lib
}  // namespace icing

#endif  // ICING_RESULT_RESULT_UTILS_H_
